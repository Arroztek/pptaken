/** Internal complexity limits. Inputs that exceed them fail closed (the whole field becomes empty). */
export const SANITIZER_LIMITS = {
  /** Slide HTML size, in UTF-16 code units (same as the schema). */
  maxHtmlLength: LIMITS.maxSlideHtml,
  /** Slide or theme CSS size, in UTF-16 code units (same as the schema). */
  maxCssLength: Math.max(LIMITS.maxSlideCss, LIMITS.maxThemeCss),
  /** Maximum element nesting depth of the parsed HTML/SVG tree. */
  maxDepth: 64,
  /** Maximum number of parsed nodes (elements + text) in one slide. */
  maxNodes: 40_000,
  /** Cost guard before parsing: attributes in one tag (duplicate detection is quadratic). */
  maxAttributesPerTag: 1024,
  /** Cost guard before parsing: estimated unclosed elements (the adoption agency walks the open stack). */
  maxUnclosedElements: 2048,
  /** Cost guard before parsing: top-level elements of the slide (parse5 adopts them quadratically). */
  maxTopLevelElements: 2000,
  /** Maximum attributes kept per element (the rest are dropped). */
  maxAttributesPerElement: 64,
  /** Maximum length of an ordinary attribute value. */
  maxAttributeLength: 2048,
  /** Maximum length of a `style` attribute value. */
  maxStyleAttributeLength: 8192,
  /** Maximum length of SVG `d`/`points`/`values` geometry data. */
  maxGeometryLength: 65_536,
  /** Maximum bracket nesting in CSS (`(`, `[`, `{`), checked before parsing. */
  maxCssNesting: 32,
  /** Maximum nesting of conditional at-rules (`@media` inside `@supports`...). */
  maxAtRuleNesting: 3,
  /** Maximum CSS rules (style rules + at-rules + keyframes) per stylesheet. */
  maxCssRules: 4000,
  /** Maximum selectors in one selector list. */
  maxSelectorsPerRule: 64,
  /** Maximum SVG `use` elements per slide. */
  maxUseElements: 500,
  /** Maximum length of a CSS string token. */
  maxCssStringLength: 512,
} as const;

