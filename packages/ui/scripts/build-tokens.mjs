#!/usr/bin/env node
// Generates dist/tokens.css and src/tokens.ts from tokens.json.
// Dependency-free: run with `node scripts/build-tokens.mjs`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));
const P = "--ppt-";
const primitives = tokens.color.primitive;

/** Resolve "{group.key}" references against color.primitive. */
export function resolve(value) {
  if (typeof value !== "string") return value;
  return value.replace(/\{([\w-]+)(?:\.([\w-]+))?\}/g, (_, group, key) => {
    const hit = key === undefined ? primitives[group] : primitives[group]?.[key];
    if (typeof hit !== "string")
      throw new Error(`Unknown token reference {${group}${key ? `.${key}` : ""}}`);
    return hit;
  });
}

const decl = (name, value) => `  ${P}${name}: ${resolve(value)};`;
const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}`;

// ---- static (theme-independent) tokens ----
const statics = [];
for (const [group, scale] of Object.entries(primitives)) {
  if (typeof scale === "string") statics.push(decl(`${group}`, scale));
  else for (const [k, v] of Object.entries(scale)) statics.push(decl(`${group}-${k}`, v));
}
for (const [k, v] of Object.entries(tokens.color.semantic.stage))
  statics.push(decl(`stage-${k}`, v));
for (const [k, v] of Object.entries(tokens.font.family)) statics.push(decl(`font-${k}`, v));
for (const [k, v] of Object.entries(tokens.font.size)) statics.push(decl(`text-${k}`, v));
for (const [k, v] of Object.entries(tokens.font.weight)) statics.push(decl(`weight-${k}`, v));
for (const [k, v] of Object.entries(tokens.font.leading)) statics.push(decl(`leading-${k}`, v));
for (const [k, v] of Object.entries(tokens.font.tracking)) statics.push(decl(`tracking-${k}`, v));
for (const [k, v] of Object.entries(tokens.space)) statics.push(decl(`space-${k}`, v));
for (const [k, v] of Object.entries(tokens.radius)) statics.push(decl(`radius-${k}`, v));
for (const [k, v] of Object.entries(tokens.border)) statics.push(decl(`border-${k}`, v));
for (const [k, v] of Object.entries(tokens.motion))
  statics.push(decl(k === "ease" ? "ease" : `motion-${k}`, v));
for (const [k, v] of Object.entries(tokens.size)) statics.push(decl(`size-${k}`, v));
for (const [k, v] of Object.entries(tokens.rhythm)) statics.push(decl(`rhythm-${k}`, v));
for (const [k, v] of Object.entries(tokens.z)) statics.push(decl(`z-${k}`, v));

// ---- themed tokens ----
const themed = (mode) => [
  ...Object.entries(tokens.color.semantic[mode]).map(([k, v]) => decl(k, v)),
  ...Object.entries(tokens.color.component[mode]).map(([k, v]) => decl(k, v)),
  ...Object.entries(tokens.shadow[mode]).map(([k, v]) => decl(`shadow-${k}`, v)),
  `  color-scheme: ${mode};`,
];

const css = [
  "/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */",
  "/* Never inject these variables into the deck iframe: the deck has its own visual world. */",
  block(":root", statics),
  block(':root,\n[data-theme="light"]', themed("light")),
  `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', themed("dark")).replace(/^/gm, "  ")}\n}`,
  block('[data-theme="dark"]', themed("dark")),
  "/* Reduced motion: every duration collapses to a short fade. */",
  `@media (prefers-reduced-motion: reduce) {\n  :root {\n    ${P}motion-fast: 1ms;\n    ${P}motion-base: 100ms;\n    ${P}motion-slow: 100ms;\n    ${P}motion-rise: 0px;\n  }\n}`,
  "",
].join("\n\n");

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "tokens.css"), css);

// ---- TypeScript constants ----
const resolveTree = (obj) =>
  Object.fromEntries(
    Object.entries(obj).map(([k, v]) => [k, typeof v === "object" ? resolveTree(v) : resolve(v)]),
  );
const { $description, ...rest } = tokens;
const ts = `// Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand.
/* eslint-disable */

/** Resolved design tokens (raw values). Prefer the CSS variables in components. */
export const tokens = ${JSON.stringify(resolveTree(rest), null, 2)} as const;

export type Tokens = typeof tokens;
export type ThemeMode = "light" | "dark";
export type SemanticColor = keyof Tokens["color"]["semantic"]["light"];

/** CSS custom property name for a token, e.g. cssVar("accent") === "var(--ppt-accent)". */
export const cssVar = (name: string): string => \`var(${P}\${name})\`;
`;
writeFileSync(join(root, "src", "tokens.ts"), ts);
console.log(`tokens: wrote dist/tokens.css (${css.length} bytes) and src/tokens.ts`);
