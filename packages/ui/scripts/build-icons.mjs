#!/usr/bin/env node
// Packs the local Phosphor SVGs in icons/ (MIT, see icons/LICENSE-phosphor.txt) into:
//   src/icons.ts    -> inner SVG markup per icon, used by Icon.svelte (inline SVG, currentColor)
//   dist/icons.css  -> CSS mask classes for static HTML (`<span class="ppt-icon" data-icon="copy">`)
// Only the icons present in icons/ are shipped. Add an icon = drop its SVG (256 viewBox) there.
// Dependency-free: `node scripts/build-icons.mjs`.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "icons");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort();

const icons = {};
for (const f of files) {
  const svg = readFileSync(join(dir, f), "utf8").trim();
  if (!/viewBox="0 0 256 256"/.test(svg))
    throw new Error(`${f}: expected a 256x256 Phosphor viewBox`);
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/\s+/g, " ")
    .trim();
  if (/<script|on\w+=/i.test(inner)) throw new Error(`${f}: unexpected active content`);
  icons[basename(f, ".svg")] = inner;
}

const ts = `// Generated by scripts/build-icons.mjs from icons/*.svg. Do not edit by hand.
// Phosphor Icons (MIT) - https://phosphoricons.com - see icons/LICENSE-phosphor.txt
export const icons = ${JSON.stringify(icons, null, 2)} as const;

export type IconName = keyof typeof icons;
`;
writeFileSync(join(root, "src", "icons.ts"), ts);

const enc = (s) =>
  encodeURIComponent(s).replace(/'/g, "%27").replace(/\(/g, "%28").replace(/\)/g, "%29");
const css = [
  "/* Generated by scripts/build-icons.mjs. Phosphor Icons (MIT). Do not edit by hand. */",
  ".ppt-icon {\n  display: inline-block;\n  flex: none;\n  width: 1.25em;\n  height: 1.25em;\n  background-color: currentColor;\n  -webkit-mask: var(--ppt-icon) center / contain no-repeat;\n  mask: var(--ppt-icon) center / contain no-repeat;\n  vertical-align: -0.25em;\n}",
  ...Object.entries(icons).map(
    ([name, inner]) =>
      `.ppt-icon[data-icon="${name}"] { --ppt-icon: url("data:image/svg+xml,${enc(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">${inner}</svg>`)}"); }`,
  ),
  "",
].join("\n");
mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "icons.css"), css);
console.log(
  `icons: packed ${files.length} icons into src/icons.ts and dist/icons.css (${css.length} bytes)`,
);
