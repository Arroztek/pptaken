// Turns the tsc output of the runtime (dist/.runtime, see tsconfig.runtime.json) into one classic script and
// embeds it as a string module (`dist/runtime-source.js`, export `RUNTIME_SOURCE`) for the document builder.
//
// No bundler: the runtime and its two dependencies (`keys`, `protocol`) have no other imports, so the modules are
// concatenated in dependency order inside an IIFE after removing their relative `import` lines and the `export`
// keywords. Indentation and blank lines are dropped (tsc already removed comments); nothing else is rewritten.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const dist = new URL("../dist/", import.meta.url);
const tmp = new URL(".runtime/", dist);
const ORDER = ["keys.js", "messages.js", "runtime.js"];

let body = "";
for (const file of ORDER) {
  let source = readFileSync(new URL(file, tmp), "utf8");
  source = source.replace(/^import \{[^}]*\} from "\.\/(keys|messages)\.js";\r?\n/gm, "");
  if (/^\s*import\b/m.test(source))
    throw new Error(`${file}: unexpected import left in the runtime`);
  source = source.replace(/^export \{\s*\};?\r?\n?/gm, "").replace(/^export /gm, "");
  if (/\bexport\b\s*[{*]/.test(source))
    throw new Error(`${file}: unexpected export left in the runtime`);
  body += `${source}\n`;
}

const compact = body
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line !== "")
  .join("\n");
const runtime = `(() => {\n"use strict";\n${compact}\n})();\n`;

// The script is inlined in an HTML <script> element: it must not be able to close it or open a comment.
if (/<\/script|<!--/i.test(runtime)) throw new Error("runtime source contains </script or <!--");

mkdirSync(dist, { recursive: true });
writeFileSync(new URL("runtime.js", dist), runtime);
writeFileSync(
  new URL("runtime-source.js", dist),
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/build-runtime.mjs. Do not edit.\nexport const RUNTIME_SOURCE = ${JSON.stringify(runtime)};\n`,
);
writeFileSync(
  new URL("runtime-source.d.ts", dist),
  "/** Source of the in-iframe runtime, a classic script for an inline `<script nonce>`. */\nexport declare const RUNTIME_SOURCE: string;\n",
);
rmSync(tmp, { recursive: true, force: true });
console.log(`runtime: ${Buffer.byteLength(runtime)} bytes`);
