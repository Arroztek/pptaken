// Turns tsc output into the two classic scripts of the player:
//
// 1. The runtime (dist/.runtime, see tsconfig.runtime.json): one IIFE embedded as a string module
//    (`dist/runtime-source.js`, exports `RUNTIME_SOURCE` and `RUNTIME_SHA256`) for the document builder. The hash
//    is what a page's CSP must allow for the runtime to run inside an offline (srcdoc) deck document.
// 2. The service worker (dist/.sw, see tsconfig.sw.json): `dist/sw.js`, served by the server at `/p/sw.js`.
//
// No bundler: each script's modules have no other imports, so they are concatenated in dependency order inside
// an IIFE after removing their relative `import` lines and the `export` keywords. Indentation and blank lines are
// dropped (tsc already removed comments); nothing else is rewritten.

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const dist = new URL("../dist/", import.meta.url);

function bundle(dir, order, label) {
  let body = "";
  for (const file of order) {
    let source = readFileSync(new URL(file, dir), "utf8");
    source = source.replace(/^import \{[^}]*\} from "\.\/[a-z-]+\.js";\r?\n/gm, "");
    if (/^\s*import\b/m.test(source))
      throw new Error(`${label}/${file}: unexpected import left in the script`);
    source = source.replace(/^export \{\s*\};?\r?\n?/gm, "").replace(/^export /gm, "");
    if (/\bexport\b\s*[{*]/.test(source))
      throw new Error(`${label}/${file}: unexpected export left in the script`);
    body += `${source}\n`;
  }
  const compact = body
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== "")
    .join("\n");
  return `(() => {\n"use strict";\n${compact}\n})();\n`;
}

mkdirSync(dist, { recursive: true });

// 1. Runtime.
const runtimeDir = new URL(".runtime/", dist);
const runtime = bundle(runtimeDir, ["keys.js", "messages.js", "runtime.js"], "runtime");
// The script is inlined in an HTML <script> element: it must not be able to close it or open a comment.
if (/<\/script|<!--/i.test(runtime)) throw new Error("runtime source contains </script or <!--");
const sha256 = createHash("sha256").update(runtime, "utf8").digest("base64");
writeFileSync(new URL("runtime.js", dist), runtime);
writeFileSync(
  new URL("runtime-source.js", dist),
  `// SPDX-License-Identifier: Apache-2.0\n// Generated by scripts/build-runtime.mjs. Do not edit.\nexport const RUNTIME_SOURCE = ${JSON.stringify(runtime)};\nexport const RUNTIME_SHA256 = ${JSON.stringify(sha256)};\n`,
);
writeFileSync(
  new URL("runtime-source.d.ts", dist),
  "/** Source of the in-iframe runtime, a classic script for an inline `<script nonce>`. */\nexport declare const RUNTIME_SOURCE: string;\n/** SHA-256 of `RUNTIME_SOURCE`, base64: the CSP hash source `'sha256-<this>'` of the runtime script. */\nexport declare const RUNTIME_SHA256: string;\n",
);
rmSync(runtimeDir, { recursive: true, force: true });

// 2. Service worker.
const swDir = new URL(".sw/", dist);
const sw = bundle(swDir, ["offline-cache.js", "sw.js"], "sw");
if (!sw.includes('"__PPTAKEN_BUILD__"')) throw new Error("sw: build placeholder missing");
writeFileSync(new URL("sw.js", dist), sw);
rmSync(swDir, { recursive: true, force: true });

console.log(`runtime: ${Buffer.byteLength(runtime)} bytes; sw: ${Buffer.byteLength(sw)} bytes`);
